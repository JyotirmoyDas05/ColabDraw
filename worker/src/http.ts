/**
 * D1 caps a row — and therefore any single string in it — at 2,000,000 bytes
 * (https://developers.cloudflare.com/d1/platform/limits/). A scene or a
 * share-link payload is stored as one row of base64 text, so anything above
 * this would pass validation and then fail inside D1 as a 500. Staying under
 * the row limit turns that into a 413 the client can explain.
 */
export const MAX_JSON_BYTES = 1_900_000;
export const MAX_FILE_BYTES = 8 * 1024 * 1024;

export const corsHeaders: Record<string, string> = {
  "access-control-allow-origin": "*",
  "access-control-allow-methods": "GET, PUT, POST, OPTIONS",
  "access-control-allow-headers": "content-type",
  "access-control-max-age": "86400",
};

export class HttpError extends Error {
  constructor(readonly status: number, readonly code: string) {
    super(code);
    this.name = "HttpError";
  }
}

export const json = (body: unknown, status = 200): Response =>
  new Response(JSON.stringify(body), {
    status,
    headers: { "content-type": "application/json; charset=utf-8" },
  });

export const fail = (status: number, code: string): Response =>
  json({ error: code }, status);

/** Ids are generated by the client, so anything outside this shape is a bug or a probe. */
export const isValidId = (id: string) => /^[A-Za-z0-9._-]{1,128}$/.test(id);

const assertDeclaredSize = (declared: string | null, maxBytes: number) => {
  if (declared && Number(declared) > maxBytes) {
    throw new HttpError(413, "payload_too_large");
  }
};

/**
 * Reads the body one chunk at a time and gives up as soon as the cap is passed.
 *
 * The declared `content-length` is checked first, so an honest oversized upload
 * is rejected before a byte is read. A chunked upload, or one that lies about
 * the header, is stopped here instead: buffering it whole first would let a
 * request larger than the isolate's memory kill the Worker, and a killed
 * isolate answers without the CORS headers the browser needs to see the error.
 */
const readCapped = async (
  request: Request,
  maxBytes: number,
): Promise<Uint8Array> => {
  assertDeclaredSize(request.headers.get("content-length"), maxBytes);

  if (!request.body) {
    return new Uint8Array(0);
  }

  const reader = request.body.getReader();
  const chunks: Uint8Array[] = [];
  let total = 0;

  for (;;) {
    const { done, value } = await reader.read();
    if (done) {
      break;
    }
    total += value.byteLength;
    if (total > maxBytes) {
      await reader.cancel();
      throw new HttpError(413, "payload_too_large");
    }
    chunks.push(value);
  }

  // One copy into an exactly-sized buffer, rather than growing and re-copying.
  const bytes = new Uint8Array(total);
  let offset = 0;
  for (const chunk of chunks) {
    bytes.set(chunk, offset);
    offset += chunk.byteLength;
  }

  return bytes;
};

export const readJson = async <T>(
  request: Request,
  maxBytes = MAX_JSON_BYTES,
): Promise<T> => {
  const text = new TextDecoder().decode(await readCapped(request, maxBytes));

  try {
    return JSON.parse(text) as T;
  } catch {
    throw new HttpError(400, "bad_request");
  }
};

export const readBytes = (
  request: Request,
  maxBytes = MAX_FILE_BYTES,
): Promise<Uint8Array> => readCapped(request, maxBytes);
